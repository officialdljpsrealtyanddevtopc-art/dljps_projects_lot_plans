-- ---------- the one function that writes sheet data ----------
-- Merges ONLY the changed fields into each lot (data || patch), so edits made in the app to other fields are never overwritten.
create or replace function public.apply_sheet_sync(
  p_patches jsonb, p_types jsonb, p_terms jsonb, p_first text, p_count int, p_by text)
returns void language plpgsql security definer set search_path = public as $$
declare k text; v jsonb;
begin
  for k, v in select * from jsonb_each(coalesce(p_patches, '{}'::jsonb)) loop
    insert into public.lots (key, data, updated_by) values (k, v, p_by)
    on conflict (key) do update set data = public.lots.data || excluded.data, updated_by = excluded.updated_by;
  end loop;

  if p_types is not null or p_terms is not null then
    insert into public.settings (id, data)
    values (1, jsonb_strip_nulls(jsonb_build_object('types', p_types, 'terms', p_terms)))
    on conflict (id) do update set data = public.settings.data
      || case when p_types is not null then jsonb_build_object('types', p_types) else '{}'::jsonb end
      || case when p_terms is not null then jsonb_build_object('terms', p_terms) else '{}'::jsonb end;
  end if;

  if p_count > 0 and p_first is not null then
    insert into public.activity (at, lot_key, field, from_val, to_val, by_name)
    values (now(), p_first, 'msg', '', 'Online sheet sync: ' || p_count || ' lots updated', p_by);
  end if;
end $$;
revoke all on function public.apply_sheet_sync(jsonb, jsonb, jsonb, text, int, text) from public, anon, authenticated;
grant execute on function public.apply_sheet_sync(jsonb, jsonb, jsonb, text, int, text) to service_role;

commit;

